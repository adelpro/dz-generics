SALT_TOKENS = frozenset({
    "CHLORHYDRATE", "SODIUM", "SODIQUE", "MONOSODIQUE", "SULFATE",
    "FUMARATE", "DICHLORHYDRATE", "MALEATE", "TRIHYDRATE", "MONOHYDRATE",
    "DIHYDRATE", "ANHYDRE", "ANHYDROUS", "POTASSIUM", "POTASSIQUE",
    "CALCIUM", "MAGNESIUM", "ACETATE", "NITRATE", "BROMURE", "CITRATE",
    "PHOSPHATE", "MESYLATE", "TOSYLATE",
})

_EXPRIME_RE = re.compile(r"\bEXPRIM\w*\s+EN\b")
_PAREN_RE = re.compile(r"\(([^()]*)\)")
_PAREN_BAD_PREFIXES = ("SOUS FORME", "OU ", "SOIT", "SEL DE")
_PAREN_BAD_TOKENS = ("RDNA", "DCI", "HBPM")
_PAREN_BAD_CHARS = "/,+"
_MAX_PAREN_TOKENS = 6


def _paren_usable(content: str) -> bool:
    """True when a parenthesised group reads as a substance, not a note."""
    if not content:
        return False
    if content in SALT_TOKENS:
        return False
    if content.startswith(_PAREN_BAD_PREFIXES):
        return False
    if any(bad in content for bad in _PAREN_BAD_TOKENS):
        return False
    if any(char in content for char in _PAREN_BAD_CHARS):
        return False
    if any(char.isdigit() for char in content):
        return False
    if len(content.split()) > _MAX_PAREN_TOKENS:
        return False
    return True


def dci_keys(dci: str | None) -> tuple[str, str]:
    """..

    The region of interest is, in order of preference, the substance stated
    after ``EXPRIME EN`` (181 DCIs put the expressed base there), the first
    parenthesised group that reads as a substance, or the whole string with
    its parens stripped. The exact key sorts the region's tokens; the base key
    additionally drops trailing salt/hydrate tokens so that
    ``CETIRIZINE DICHLORHYDRATE`` groups with ``CETIRIZINE`` without ever
    colliding at the exact level. Unrecognised suffixes stay in the base.

    Parentheses are read from the *raw* string: ``fold`` collapses them to
    spaces, so the paren scan has to run before folding.
    """
    raw = "" if dci is None else str(dci)
    folded = fold(raw)

    region = ""
    marker = _EXPRIME_RE.search(folded)
    if marker is not None:
        region = folded[marker.end():].strip()

    if not region:
        for content in _PAREN_RE.findall(raw):
            candidate = fold(content)
            if _paren_usable(candidate):
                region = candidate
                break

    if not region:
        region = fold(_PAREN_RE.sub(" ", raw))

    tokens = region.split()
    exact = " ".join(sorted(tokens))
    base_tokens = list(tokens)
    while base_tokens and base_tokens[-1] in SALT_TOKENS:
        base_tokens.pop()
    base = " ".join(sorted(base_tokens))
    return exact, base