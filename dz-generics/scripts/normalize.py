_NUMBER_RE = re.compile(r"(?:\d{1,3}(?: \d{3})+|\d+)(?:[.,]\d+)?")
_UNIT_RE = re.compile(r"[A-Za-zµμ]{1,12}%?|%")
_UNIT_IN_MG = {"G": 1000.0, "MG": 1.0, "µG": 0.001, "UG": 0.001, "MCG": 0.001}


def _to_number(raw: str) -> float:
    return float(raw.replace(" ", "").replace(",", "."))


def _fmt(value: float) -> str:
    """Format a float without ever falling into scientific notation."""
    return f"{value:.10f}".rstrip("0").rstrip(".")


def dose_key(dosage: str | None) -> str | None:
    """Canonical strength key, or ``None`` when the dosage carries no number.

    ``None`` means *unknown*: the 22 rows without a digit (19 blanks, ``n``,
    ``---``, ``q.s pour un flacon``) are quantum-satis rows whose amount is
    fixed at dispensing time. Callers must treat ``None`` as unknown, not as
    a mismatch.

    The first number+unit wins. ``X per Y`` ratios divide to a base
    concentration only when the denominator unit is ML, so 5MG/5ML groups
    with 1MG/ML but 80MG/12,5MG stays distinct from 160MG/25MG.
    """
    if dosage is None:
        return None
    text = str(dosage)
    if not text.strip():
        return None

    match = _NUMBER_RE.search(text)
    if match is None:
        return None
    value = _to_number(match.group(0))
    after_number = text[match.end():]

    unit_match = _UNIT_RE.match(after_number)
    unit = unit_match.group(0).upper() if unit_match else ""
    tail = after_number[unit_match.end():] if unit_match else after_number

    denominator_value = None
    denominator_unit = ""
    denominator_had_number = False
    if tail.startswith("/"):
        den_tail = tail[1:]
        den_match = _NUMBER_RE.match(den_tail)
        position = 0
        if den_match is not None:
            denominator_value = _to_number(den_match.group(0))
            position = den_match.end()
            denominator_had_number = True
        den_unit_match = _UNIT_RE.match(den_tail[position:])
        if den_unit_match is not None:
            denominator_unit = den_unit_match.group(0).upper()

    if unit and not unit.endswith("%") and unit in _UNIT_IN_MG:
        value *= _UNIT_IN_MG[unit]
        unit = "MG"

    if denominator_unit == "ML":
        divisor = denominator_value if denominator_had_number else 1.0
        return f"{_fmt(value / divisor)}MG/ML"

    if denominator_unit:
        parts = [f"{_fmt(value)}{unit}"]
        if denominator_had_number:
            parts.append(f"{_fmt(denominator_value)}{denominator_unit}")
        else:
            parts.append(denominator_unit)
        return "/".join(parts)

    return f"{_fmt(value)}{unit}"


