def form_key(form: str | None) -> str:
    """Canonical key for a dosage form.

    Exact re-spelling from ``FORM_CANON`` wins; otherwise the tail resolves
    through token-level abbreviation expansion; otherwise the folded text is
    the key itself (every non-form keeps its own key).
    """
    folded = fold(form)
    canonical = FORM_CANON.get(folded)
    if canonical is None:
        tokens = folded.split()
        if any(token in _FORM_TOKENS for token in tokens):
            canonical = _form_token_expand(tokens)
        else:
            canonical = folded
    return canonical.replace(" ", "_")


