# A dosage is read as a *strength expression*: at most two number+unit terms
# joined by a single '/'. Everything past that is a different expression and is
# ignored, which is what stops a restated second notation from relabelling the
# dose -- `100UI/ML (3.5MG/ML)` was keying `100MG/ML`, taking the value from
# the first term and the unit from the second.
#
# A unit is MANDATORY. Without one, a mass, a concentration, a percentage and a
# volume all collapse onto the same bare number, and the key stops meaning
# anything: 0,25 µg, 0.25 MG/ML and 0.5 ML all keyed `0.25`/`0.5`, so a user
# comparing two products was told a 0.5 mL volume, a 0.5 mg mass and a 0.5%
# concentration were one dose. A bare number is not a dose identity, so it is
# `None` -- unknown, never a mismatch.

# Thousands are space-separated in this file (1 500 000UI), decimals use either
# a comma (1025 rows) or a period.
_NUMBER_RE = re.compile(r"(?:\d{1,3}(?: \d{3})+|\d+)(?:[.,]\d+)?")
# A unit is letters with an optional %, and may carry the file's footnote
# markers: MG, MG**, %, G%, µG. The leading \s* is load-bearing -- 10 UI/ML and
# 60 MG/1.5 ML are common, and matching the unit against the raw remainder with
# no space tolerance is what made every spaced value lose its unit.
_UNIT_RE = re.compile(r"\s*([A-Za-zµμΜ]+%?|%)\**")
_PAREN_GROUP_RE = re.compile(r"\([^()]*\)")
_COMPARTMENT_RE = re.compile(r"\bCOMPARTIMENT\b", re.IGNORECASE)
_PLUS_RE = re.compile(r"\+")
# A top-level dash immediately followed by a number: a second dose, not a
# hyphen. The digit lookahead is what keeps ``74,4MG/SACHET- DOSE`` out.
_DASH_DOSE_RE = re.compile(r"-\s*\d")

# Only exact, dimensionally-safe conversions. G->MG, µg/ug/mcg->MG.
# UI and U are NOT here and must never be: the UI->mg factor is substance
# specific (insulin 1 UI ~= 0.034 mg) and dose_key has no DCI to consult. Same
# for IR, MUI, KUI, MMOL/MMOLE, KBq/MBq -- 30MUI/0,5ML was keying 60MG/ML and
# 0,1IR/ML was keying 0,1MG/ML. Percentages stay percentages: without knowing
# the basis, a mass fraction is not interchangeable with them.
_MASS_TO_MG = {"G": 1000.0, "MG": 1.0, "µG": 0.001, "UG": 0.001, "MCG": 0.001}
_MASS_UNIT = "MG"
_VOLUME_UNIT = "ML"


def _to_number(raw: str) -> float:
    return float(raw.replace(" ", "").replace(",", "."))


def _fmt(value: float) -> str:
    """Format a float without ever falling into scientific notation."""
    return f"{value:.10f}".rstrip("0").rstrip(".")


def _clean_unit(raw: str) -> str:
    """Normalise a matched unit blob so that table lookups actually hit.

    ``str.upper()`` turns MICRO SIGN into GREEK CAPITAL LETTER MU, so ``µG``
    came out as ``ΜG``, missed the conversion table, and 1000µG/ML keyed
    1000MG/ML -- a factor of 1000 on a real row. Undo that, then drop the
    footnote markers and any trailing period (FL.).
    """
    return raw.upper().replace("Μ", "µ").rstrip("*. ")


def _is_multi_ingredient(text: str) -> bool:
    """True when the strength names more than one active at top level.

    Fixed-dose combinations cannot be identified from the dosage column alone
    -- which of the actives matches is undecidable -- so any single key is a
    guess. A ``+`` *outside* parentheses always means a second active in this
    file. A ``+`` *inside* parentheses does not: it decomposes one substance
    into its parts, and three rows depend on that --
    ``500MG**  ( sel 167MG+375MG)`` (one salt, stated both ways),
    ``120MG** DE MAGNESIUM ELEMENT (SOIT 1078MG DE LACTATE ... + 125MG DE
    CITRATE ...)`` (one element, two salts) and ``567,7MG ... Fer (2+) 100MG``
    (an oxidation state, not an addition). Flagging those would discard a
    single-ingredient strength to protect nothing.

    A top-level ``-`` followed by a number is a second *dose* rather than a
    second active: a titration schedule, which the first-expression rule
    would otherwise flatten onto its opening term. Two different schedules
    landed on one key that way. The digit lookahead keeps the hyphen out of
    it (``74,4MG/SACHET- DOSE`` keeps its key), and blanking the bracketed
    groups keeps a reconstitution table out of it, so
    ``5MG/ML (100MG/20ML - 500MG/100ML)`` still keys the stock concentration
    ``5MG/ML`` -- the right answer for all 23 rows in the workbook that
    state a dash inside brackets.
    """
    if _COMPARTMENT_RE.search(text):
        return True
    top_level = _PAREN_GROUP_RE.sub(" ", text)
    return bool(_PLUS_RE.search(top_level)
                or _DASH_DOSE_RE.search(top_level))


def _read_term(text: str, start: int = 0) -> tuple[float | None, str, int]:
    """One ``[number][unit]`` term at ``start``.

    Returns ``(value, unit, end)``. ``value`` is ``None`` for a unit written
    without a number (``10MG/ML``); ``unit`` is ``""`` when nothing follows the
    number; ``end`` is the offset just past the term, so a caller can tell a
    denominator from the start of a new expression.
    """
    number = _NUMBER_RE.match(text, start)
    if number is None:
        value, cursor = None, start
    else:
        value, cursor = _to_number(number.group(0)), number.end()

    unit_match = _UNIT_RE.match(text, cursor)
    if unit_match is None:
        return value, "", cursor
    return value, _clean_unit(unit_match.group(1)), unit_match.end()


def _as_mass(value: float, unit: str) -> tuple[float, str]:
    """Put a term on the MG basis, or leave it alone when it is not a mass.

    Returning the original ``(value, unit)`` unchanged is what stops the ratio
    reduction from relabelling a non-mass numerator.
    """
    factor = _MASS_TO_MG.get(unit)
    if factor is None:
        return value, unit
    return value * factor, _MASS_UNIT


def _concentration(value: float, unit: str, divisor: float) -> str:
    """``X per mL`` reduced to one base concentration, numerator intact."""
    mass, mass_unit = _as_mass(value, unit)
    return f"{_fmt(mass / divisor)}{mass_unit}/{_VOLUME_UNIT}"


def dose_key(dosage: str | None) -> str | None:
    """Canonical strength key, or ``None`` when the dose is not determinable.

    ``None`` means *unknown*, never a mismatch. Callers must not read it as
    "different strength". Two families reach it:

    - 22 rows carry no number at all (19 blanks, ``n``, ``---``,
      ``q.s pour un flacon``) -- quantum satis, the amount is fixed at
      dispensing time;
    - any dosage written as a bare number has no determinable dimension, so it
      is unknown too. That is the majority of the unparsed rows and it is the
      correct answer: a bare ``0.02`` could be 20 mg, 20% or 20 mL.

    The first strength expression wins and the rest is dropped. An ``X per Y``
    ratio divides to a base concentration only when the denominator is a
    volume, so 5MG/5ML groups with 1MG/ML but 80MG/12,5MG stays distinct from
    160MG/25MG -- both would otherwise reduce to 6.4.
    """
    if dosage is None:
        return None
    text = str(dosage).strip()
    if not text or _is_multi_ingredient(text):
        return None

    value, unit, end = _read_term(text)
    if value is None or not unit:
        return None

    denominator = None
    if text[end:end + 1] == "/":
        d_value, d_unit, _ = _read_term(text, end + 1)
        if d_unit:
            denominator = (d_value, d_unit)

    if denominator is None:
        mass, mass_unit = _as_mass(value, unit)
        return f"{_fmt(mass)}{mass_unit}"

    d_value, d_unit = denominator
    if d_unit == _VOLUME_UNIT:
        return _concentration(value, unit, d_value if d_value is not None else 1.0)

    # A ratio that is not a concentration keeps both terms, so two mixtures
    # that happen to divide to the same number stay apart.
    mass, mass_unit = _as_mass(value, unit)
    left = f"{_fmt(mass)}{mass_unit}"
    if d_value is None:
        return f"{left}/{d_unit}"
    d_mass, d_mass_unit = _as_mass(d_value, d_unit)
    return f"{left}/{_fmt(d_mass)}{d_mass_unit}"


