"""Normalization layer for the Algerian nomenclature (Task 2 of the dz-generics plan).

Pure functions with no I/O and no database access -- later tasks call them by
these exact names. Everything here is derived from the observed ministry file
(`references/schema.md` + the full distributions printed by
`profile_source.py`), not from a guessed vocabulary.

Public surface
--------------
- ``fold``        : NFKD, drop combining marks, uppercase, collapse every
                    non-alphanumeric run to a single space, strip. Accents no
                    longer separate spellings; punctuation no longer does.
- ``FORM_CANON``  : redirection table built from the observed FORME values.
                    Keys are *folded* forms; values are the canonical form's
                    folded tokens. Abbreviations, misspellings and non-forms
                    redirect; already-canonical spellings map to themselves
                    implicitly.
- ``form_key``    : canonical key for a dosage form. The placeholder ``FORME``
                    and the empty/``---`` buckets collapse to ``NON_SPECIFIE``
                    (they are *unknown*, not a form). Non-forms such as FLACON
                    and LAIT EN POUDRE keep their own keys.
- ``dose_key``    : canonical strength key, or ``None`` when the dose is not
                    determinable -- no number at all (22 rows), no unit after
                    the number (every bare-number dosage), or several actives
                    in one cell. ``None`` means *unknown*, never a mismatch.
- ``dci_keys``    : ``(exact, base)`` pair for a DCI. The exact key sorts the
                    tokens of the chosen substance region alphabetically; the
                    base key additionally drops trailing salt/hydrate tokens,
                    so CETIRIZINE DICHLORHYDRATE groups with CETIRIZINE while
                    staying distinct at the exact level.

Design notes for readers (all decisions are evidence-backed):

- **A dosage key always carries a unit.** A bare number is not a dose
  identity: 0,25 µg, 0.25 MG/ML and 0.5 ML all keyed a bare ``0.25``/``0.5``,
  so a 0.5 mL volume, a 0.5 mg mass and a 0.5% concentration came out equal.
  No unit found means ``None``.
- **A space between the number and the unit is not significant.** ``10 UI/ML``
  and ``10UI/ML`` are the same; ``60 MG/1.5 ML`` is ``40MG/ML``.
- **Only the first strength expression is read.** ``100UI/ML (3.5MG/ML)`` was
  keying ``100MG/ML`` -- the value came from the first term and the unit from
  the second.
- A ``X per Y`` ratio is divided to a base concentration *only* when the
  denominator unit is ML. 5MG/5ML is 1 MG/ML; the ministry writes the same
  strength both ways. Dividing 80MG/12,5MG and 160MG/25MG would wrongly merge
  them (both reduce to 6.4), so non-ML denominators stay as a number/unit pair.
- **Only exact conversions happen: G and µg/ug/mcg to MG.** Percentages stay
  percentages. UI, U, IR, MUI, KUI, MMOL, KBq are not masses and are never
  relabelled -- the UI-to-mg factor is substance-specific and dose_key has no
  DCI. Dividing must keep the numerator's own unit: 30MUI/0,5ML is
  ``60MUI/ML``, not ``60MG/ML``.
- Decimal comma and decimal dot both mean decimal -- 1025 rows use a comma.
  Thousands are space-separated in this file (``1 500 000UI``), so a leading
  ``1`` followed by space-separated triples is one number.
- ``dci_keys`` prefers (1) the substance stated after ``EXPRIME EN``, then
  (2) the first parenthesised group that is a plausible substance (the guard
  rejects concentration notes, salt names, and token lists such as
  ``VIT.B9``), else (3) the whole string with its parens stripped.

The salt table is the French-preference list the brief pins: the file prefers
``SODIQUE`` (31 rows) over ``SODIUM`` and ``ANHYDRE`` (26) over ``ANHYDROUS``.
An unrecognised suffix stays in the substance -- dropping a token that is not
a salt merges two genuinely different drugs, which is the worse error.
"""

from __future__ import annotations

import re
import unicodedata

# ---------------------------------------------------------------------------
# fold
# ---------------------------------------------------------------------------

_NON_ALNUM = re.compile(r"[^A-Z0-9]+")


def fold(text: str | None) -> str:
    """Uppercase and drop accents and punctuation so spellings compare equal.

    ``None`` folds to ``""`` -- callers never have to branch on it.
    """
    if text is None:
        return ""
    decomposed = unicodedata.normalize("NFKD", str(text))
    ascii_text = "".join(ch for ch in decomposed if not unicodedata.combining(ch)).upper()
    return _NON_ALNUM.sub(" ", ascii_text).strip()


